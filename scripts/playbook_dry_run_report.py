"""Summarise the playbook results in the throwaway dry-run database (made by
`python -m scripts.extract_preview --fake`) into docs/phase4-dry-run.md. No API calls."""

import os
from collections import Counter, defaultdict
from pathlib import Path

from sqlalchemy import create_engine, select
from sqlalchemy.engine import make_url

from app.db import sqlalchemy_url
from app.models import Document, Extraction
from scripts.extract_preview import DRY_RUN_DB, _use_local_database

OUT = Path(__file__).resolve().parents[1] / "docs" / "phase4-dry-run.md"


def main() -> None:
    _use_local_database()
    url = make_url(sqlalchemy_url(os.environ["DATABASE_URL"])).set(database=DRY_RUN_DB)
    with create_engine(url).connect() as conn:
        rows = conn.execute(
            select(
                Document.__table__.c.status,
                Document.__table__.c.doc_type,
                Extraction.__table__.c.playbook_results,
                Extraction.__table__.c.review_reasons,
            ).join(
                Extraction.__table__, Extraction.__table__.c.document_id == Document.__table__.c.id
            )
        ).all()

    statuses = Counter(r.status for r in rows)
    nda_statuses = Counter(r.status for r in rows if r.doc_type == "nda")
    per_rule: dict[str, Counter] = defaultdict(Counter)
    reasons = Counter()
    for r in rows:
        for res in r.playbook_results or []:
            per_rule[res["rule_id"]][res["outcome"]] += 1
        for reason in r.review_reasons:
            reasons[reason["code"]] += 1
    n_nda = sum(nda_statuses.values())

    lines = [
        "# Phase 4 dry run (fake extractor)",
        "",
        "> **FAKE-EXTRACTOR OUTPUT, NOT REAL ACCURACY.** No model was called. A test double answered"
        " every document from the synthetic manifest's ground truth, like a perfect model would,"
        " so the playbook outcomes below are the manifest's deviations passing through the real"
        " pipeline (parse -> verify -> playbook check -> routing). They show the plumbing works,"
        " not how well a model reads NDAs. Real numbers need `make extract-preview` (not run).",
        "",
        "> Generated by `python -m scripts.extract_preview --fake` then"
        " `python -m scripts.playbook_dry_run_report`, on the same 20-document sample as"
        " `docs/phase3-dry-run.md`, in a throwaway database.",
        "",
        f"{len(rows)} documents, {n_nda} of them NDAs (the playbook only applies to NDAs).",
        "",
        "## Documents per final status",
        "",
        "| Status | All documents | NDAs |",
        "|---|---|---|",
    ]
    for status in sorted(statuses):
        lines.append(f"| {status} | {statuses[status]} | {nda_statuses.get(status, 0)} |")
    lines += [
        "",
        "## Playbook outcome per rule (NDAs only)",
        "",
        "| Rule | pass | deviation | unknown |",
        "|---|---|---|---|",
    ]
    for rule, c in per_rule.items():
        lines.append(f"| `{rule}` | {c['pass']} | {c['deviation']} | {c['unknown']} |")
    lines += ["", "## Review reasons (all documents)", "", "| Code | Count |", "|---|---|"]
    for code, n in reasons.most_common():
        lines.append(f"| `{code}` | {n} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
